// SERVER CONTROL MODE COMMANDS (0x34)
// All writes go to the 0x34 Set command.  The Flags bytes (packet[6-7]) tell
// the FTC which data fields are valid in this packet.  Status read-back comes
// from the 0x28 response at the same packet indices.
//
// Packet layout for 0x34 (indices are into the full UART packet):
//   [5]=0x34  [6]=FlagsByte1  [7]=FlagsByte2
//   [8]=DHW   [9]=HOL  [10]=IDHW  [11]=Z1HI  [12]=Z1CI
//   [13]=Z2HI  [14]=CZ2I  [15]=SCM  [16..20]=MEL,Unk2-5
//
// To activate any prohibit the FTC requires Server Control Mode (SCM) to be ON.
// All prohibit commands below therefore pre-set SCM=1 (packet[15]=0x01) in the
// mask and include the 0x80 SCM flag bit so the FTC registers the SCM change
// in the same packet.  Turning a prohibit switch OFF still keeps SCM=1 in the
// transmitted packet (SCM is only cleared via the server_control_mode switch).

// Server Control Mode — enable/disable independently.
// Flags: 0x80 (SCM only). varIndex 15 = SCM data byte.
DEFINE_COMMAND(server_control_mode, 15, CommandVarType_ON_OFF, SINGLE_ARG({0xfc, 0x41, 0x02, 0x7a, 0x10, 0x34, 0x80, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00}));

